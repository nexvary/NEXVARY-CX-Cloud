#!/usr/bin/env bash
# Nginx reverse proxy and optional HTTPS configuration

set -euo pipefail

readonly NX_NGINX_CONF_DIR='/etc/nginx/conf.d'
readonly NX_NGINX_SITE='nexvary-cx'

# ── PHP-FPM socket detection ──────────────────────────────────────────────────

nx_php_fpm_socket() {
  # Return the pre-computed socket path when nx_configure_php_fpm has run.
  # This ensures the pool config and all nginx upstreams always use the same path.
  if [[ -n "${NX_FPM_SOCKET:-}" ]]; then
    echo "${NX_FPM_SOCKET}"
    return
  fi
  # Try known socket paths
  local candidates=(
    "/run/php/php8.3-fpm.sock"
    "/var/run/php-fpm/www.sock"
    "/var/run/php-fpm.sock"
    "/tmp/php-fpm.sock"
  )
  for s in "${candidates[@]}"; do
    if [[ -S "$s" ]]; then
      echo "$s"
      return
    fi
  done
  # Fallback to TCP
  echo "127.0.0.1:9000"
}

# ── Write Nginx site configuration ───────────────────────────────────────────

nx_configure_nginx() {
  nx_step "Configuring Nginx reverse proxy"

  local domain="${NX_DOMAIN:-localhost}"
  local fpm_socket; fpm_socket="$(nx_php_fpm_socket)"
  local conf_file="${NX_NGINX_CONF_DIR}/${NX_NGINX_SITE}.conf"

  # Remove any existing default site that conflicts
  rm -f /etc/nginx/sites-enabled/default \
        /etc/nginx/conf.d/default.conf 2>/dev/null || true

  # Back up any existing config so we can restore it if nginx -t fails
  local _bak="${conf_file}.bak-$(date +%s)"
  if [[ -f "$conf_file" ]]; then cp "$conf_file" "$_bak"; fi

  cat > "$conf_file" <<NGINX
# NEXVARY CX Cloud — Nginx configuration
# Generated by installer on $(date -Iseconds)

server {
    listen 80;
    listen [::]:80;
    server_name ${domain};

    root ${NX_APP_DIR:-/var/www/nexvary-cx}/public;
    index index.php;

    # Security headers
    add_header X-Frame-Options           "SAMEORIGIN"      always;
    add_header X-Content-Type-Options    "nosniff"         always;
    add_header X-XSS-Protection          "1; mode=block"   always;
    add_header Referrer-Policy           "strict-origin"   always;

    # Logs
    access_log /var/log/nginx/nexvary-access.log;
    error_log  /var/log/nginx/nexvary-error.log;

    location / {
        try_files \$uri \$uri/ /index.php?\$query_string;
    }

    location = /favicon.ico { access_log off; log_not_found off; }
    location = /robots.txt  { access_log off; log_not_found off; }

    # Static assets — long cache
    location ~* \.(css|js|woff2?|ttf|eot|svg|png|jpg|jpeg|gif|ico|webp|avif)\$ {
        expires 1y;
        add_header Cache-Control "public, immutable";
        try_files \$uri =404;
    }

    location ~ \.php\$ {
        fastcgi_pass   ${fpm_socket};
        fastcgi_param  SCRIPT_FILENAME \$realpath_root\$fastcgi_script_name;
        include        fastcgi_params;
        fastcgi_index  index.php;
        fastcgi_buffers 16 16k;
        fastcgi_buffer_size 32k;
        fastcgi_read_timeout 120;
    }

    # Deny access to hidden files
    location ~ /\. {
        deny all;
        access_log off;
        log_not_found off;
    }

    # Deny direct access to .env, composer files
    location ~ \.(env|json|lock|md)\$ {
        deny all;
    }
}
NGINX

  # On systems using sites-enabled
  if [[ -d /etc/nginx/sites-enabled ]]; then
    ln -sf "$conf_file" "/etc/nginx/sites-enabled/${NX_NGINX_SITE}.conf"
  fi

  if nginx -t 2>&1 | nx_log_passthrough; then
    rm -f "$_bak" 2>/dev/null || true
    systemctl reload nginx
  else
    nx_error "Nginx config test failed — restoring previous state"
    if [[ -f "$_bak" ]]; then mv "$_bak" "$conf_file"; else rm -f "$conf_file"; fi
    nginx -t 2>/dev/null || true
    nx_fatal "Nginx configuration invalid — rolled back"
  fi
  nx_ok "Nginx configured for http://${domain}/"
}

# ── PHP-FPM pool configuration ────────────────────────────────────────────────

nx_configure_php_fpm() {
  nx_step "Configuring PHP-FPM pool for NEXVARY"

  local pool_dir
  pool_dir="$(find /etc/php* -type d -name 'pool.d' 2>/dev/null | head -1 || echo '')"
  if [[ -z "$pool_dir" ]]; then
    nx_warn "PHP-FPM pool directory not found — skipping pool configuration"
    return
  fi

  # Use a dedicated, app-specific socket name to avoid colliding with the
  # default www pool (which also lives in /run/php/).  The path is fixed and
  # does not depend on the installed PHP version.
  export NX_FPM_SOCKET='/run/php/nexvary-cx.sock'

  # Detect the user nginx runs as so the socket permissions allow connection.
  local nginx_user='www-data'
  if getent passwd nginx &>/dev/null; then nginx_user='nginx'; fi

  cat > "${pool_dir}/nexvary-cx.conf" <<FPM
; NEXVARY CX Cloud PHP-FPM pool — dedicated socket, does not replace www pool
[nexvary-cx]
user  = ${NX_APP_USER:-nexvary}
group = ${NX_APP_USER:-nexvary}

listen = ${NX_FPM_SOCKET}
listen.owner = ${nginx_user}
listen.group = ${nginx_user}
listen.mode  = 0660

pm = dynamic
pm.max_children      = 10
pm.start_servers     = 2
pm.min_spare_servers = 1
pm.max_spare_servers = 5
pm.max_requests      = 500

request_terminate_timeout = 60s
chdir = ${NX_APP_DIR:-/var/www/nexvary-cx}

php_admin_value[error_log] = ${NX_APP_DIR:-/var/www/nexvary-cx}/storage/logs/php-fpm.log
php_admin_flag[log_errors]  = on
php_flag[display_errors]    = off
FPM

  # Leave the default www pool intact so other services on the host are
  # unaffected.  The nexvary-cx pool uses its own socket and pool name.

  # Start/restart PHP-FPM
  local fpm_svc; fpm_svc="$(systemctl list-units 'php*-fpm*' --no-legend 2>/dev/null | awk '{print $1}' | head -1)"
  if [[ -n "$fpm_svc" ]]; then
    systemctl enable "$fpm_svc" --now 2>/dev/null || true
    systemctl restart "$fpm_svc" 2>/dev/null || true
  fi

  nx_ok "PHP-FPM pool 'nexvary-cx' configured"
}

# ── HTTPS using an existing Let's Encrypt certificate ─────────────────────────
# Called when NX_DOMAIN already has a valid cert in /etc/letsencrypt/live/.
# Writes port-80 redirect + port-443 SSL server blocks without calling certbot.
# Any pre-existing Nginx site that claims the same server_name is backed up
# (not deleted) so automatic cert renewal keeps working.

nx_configure_nginx_https() {
  nx_step "Configuring Nginx with existing Let's Encrypt certificate"

  local domain="${NX_DOMAIN:-}"
  if [[ -z "$domain" || "$domain" == 'localhost' ]]; then
    nx_fatal "NX_DOMAIN must be set to a real FQDN when reusing an existing certificate."
  fi

  local cert_dir="/etc/letsencrypt/live/${domain}"
  local fullchain="${cert_dir}/fullchain.pem"
  local privkey="${cert_dir}/privkey.pem"

  if [[ ! -f "$fullchain" || ! -f "$privkey" ]]; then
    nx_fatal "Let's Encrypt certificate not found for ${domain}.\n  Expected: ${fullchain}\n  Run certbot manually or pass --https=certbot to request one."
  fi
  nx_ok "Certificate found: ${fullchain}"

  local fpm_socket; fpm_socket="$(nx_php_fpm_socket)"
  local conf_file="${NX_NGINX_CONF_DIR}/${NX_NGINX_SITE}.conf"

  # Back up any existing site config that claims this domain to prevent
  # duplicate server_name conflicts while keeping it reversible.
  local stamp; stamp="$(date +%Y%m%d%H%M%S)"
  for f in /etc/nginx/sites-enabled/* /etc/nginx/conf.d/*.conf; do
    [[ -f "$f" ]] || continue
    [[ "$(realpath "$f" 2>/dev/null)" == "$(realpath "$conf_file" 2>/dev/null)" ]] && continue
    if grep -q "server_name[[:space:]].*${domain}" "$f" 2>/dev/null; then
      nx_warn "Disabling conflicting Nginx site: $f (backed up as ${f}.pre-nexvary-${stamp})"
      mv "$f" "${f}.pre-nexvary-${stamp}"
    fi
  done
  rm -f /etc/nginx/sites-enabled/default \
        /etc/nginx/conf.d/default.conf 2>/dev/null || true

  cat > "$conf_file" <<NGINX
# NEXVARY CX Cloud — Nginx HTTPS configuration
# Generated by installer on $(date -Iseconds)
# Certificate: ${fullchain}

# Redirect all HTTP to HTTPS (preserves automatic cert renewal via /.well-known)
server {
    listen 80;
    listen [::]:80;
    server_name ${domain};

    location /.well-known/acme-challenge/ {
        root /var/www/html;
    }

    location / {
        return 301 https://\$host\$request_uri;
    }
}

server {
    listen 443 ssl;
    listen [::]:443 ssl;
    http2 on;
    server_name ${domain};

    ssl_certificate     ${fullchain};
    ssl_certificate_key ${privkey};
    ssl_protocols       TLSv1.2 TLSv1.3;
    ssl_ciphers         ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384;
    ssl_prefer_server_ciphers off;
    ssl_session_cache   shared:SSL:10m;
    ssl_session_timeout 1d;
    ssl_stapling        on;
    ssl_stapling_verify on;

    add_header Strict-Transport-Security "max-age=63072000; includeSubDomains" always;
    add_header X-Frame-Options           "SAMEORIGIN"      always;
    add_header X-Content-Type-Options    "nosniff"         always;
    add_header Referrer-Policy           "strict-origin"   always;

    root ${NX_APP_DIR:-/var/www/nexvary-cx}/public;
    index index.php;

    access_log /var/log/nginx/nexvary-access.log;
    error_log  /var/log/nginx/nexvary-error.log;

    location / {
        try_files \$uri \$uri/ /index.php?\$query_string;
    }

    location = /favicon.ico { access_log off; log_not_found off; }
    location = /robots.txt  { access_log off; log_not_found off; }

    location ~* \.(css|js|woff2?|ttf|eot|svg|png|jpg|jpeg|gif|ico|webp|avif)\$ {
        expires 1y;
        add_header Cache-Control "public, immutable";
        try_files \$uri =404;
    }

    location ~ \.php\$ {
        fastcgi_pass   ${fpm_socket};
        fastcgi_param  SCRIPT_FILENAME \$realpath_root\$fastcgi_script_name;
        include        fastcgi_params;
        fastcgi_index  index.php;
        fastcgi_buffers 16 16k;
        fastcgi_buffer_size 32k;
        fastcgi_read_timeout 120;
    }

    location ~ /\. {
        deny all;
        access_log off;
        log_not_found off;
    }

    location ~ \.(env|json|lock|md)\$ {
        deny all;
    }
}
NGINX

  if [[ -d /etc/nginx/sites-enabled ]]; then
    ln -sf "$conf_file" "/etc/nginx/sites-enabled/${NX_NGINX_SITE}.conf"
  fi

  if nginx -t 2>&1 | nx_log_passthrough; then
    systemctl reload nginx
  else
    nx_error "Nginx HTTPS config test failed — restoring previous state"
    for f_bak in /etc/nginx/sites-enabled/*.pre-nexvary-"${stamp}" \
                 /etc/nginx/conf.d/*.pre-nexvary-"${stamp}"; do
      [[ -f "$f_bak" ]] || continue
      mv "$f_bak" "${f_bak%.pre-nexvary-${stamp}}" 2>/dev/null || true
    done
    rm -f "$conf_file" 2>/dev/null || true
    nginx -t 2>/dev/null || true
    nx_fatal "Nginx HTTPS configuration invalid — rolled back"
  fi
  nx_ok "Nginx configured for https://${domain}/"

  # Update APP_URL to HTTPS so QR pairing targets the right origin
  local env_file="${NX_APP_DIR:-/var/www/nexvary-cx}/.env"
  if [[ -f "$env_file" ]]; then
    sed -i "s|^APP_URL=.*|APP_URL=https://${domain}|" "$env_file"
    nx_ok "APP_URL set to https://${domain}"
  fi
}

# ── HTTPS via Certbot ─────────────────────────────────────────────────────────

nx_configure_https_certbot() {
  local domain="${NX_DOMAIN:-}"
  local email="${NX_CERTBOT_EMAIL:-}"

  if [[ -z "$domain" || "$domain" == 'localhost' ]]; then
    nx_warn "HTTPS via Let's Encrypt requires a real domain name. Skipping HTTPS."
    nx_warn "Set NX_DOMAIN=your.domain.com and NX_CERTBOT_EMAIL=you@example.com to enable HTTPS."
    return 0
  fi

  if ! command -v certbot &>/dev/null; then
    nx_warn "certbot not found — HTTPS will not be configured automatically."
    return 0
  fi

  nx_step "Requesting Let's Encrypt TLS certificate for ${domain}"
  nx_info "Certbot will configure HTTPS. This requires port 80 to be accessible from the internet."

  local certbot_args=(
    certonly --nginx
    --non-interactive --agree-tos
    --redirect
    -d "$domain"
  )
  if [[ -n "$email" ]]; then
    certbot_args+=(--email "$email")
  else
    certbot_args+=(--register-unsafely-without-email)
  fi

  if certbot "${certbot_args[@]}" 2>&1 | nx_log_passthrough; then
    nx_ok "TLS certificate obtained for $domain"

    # Update APP_URL in .env
    local env_file="${NX_APP_DIR:-/var/www/nexvary-cx}/.env"
    if [[ -f "$env_file" ]]; then
      sed -i "s|^APP_URL=.*|APP_URL=https://${domain}|" "$env_file"
    fi
  else
    nx_warn "Certbot failed. The app will continue on HTTP. Run certbot manually later."
  fi
}

# ── Self-signed certificate for localhost ─────────────────────────────────────

nx_configure_https_selfsigned() {
  if [[ "${NX_HTTPS:-}" != 'selfsigned' ]]; then return 0; fi

  nx_step "Generating self-signed TLS certificate (development only)"
  local cert_dir='/etc/ssl/nexvary'
  mkdir -p "$cert_dir"

  openssl req -x509 -nodes -newkey rsa:2048 -days 365 \
    -keyout "${cert_dir}/privkey.pem" \
    -out    "${cert_dir}/fullchain.pem" \
    -subj   "/C=XX/O=NEXVARY/CN=${NX_DOMAIN:-localhost}" \
    2>/dev/null

  chmod 600 "${cert_dir}/privkey.pem"
  nx_warn "Self-signed certificate created. Browsers will show a security warning."
  nx_ok "Self-signed TLS certificate generated"
}
